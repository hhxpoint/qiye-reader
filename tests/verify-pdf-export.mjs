import { registerHooks } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
registerHooks({ resolve(specifier, context, nextResolve) { if (specifier.startsWith('.') && !/\.[a-z]+$/i.test(specifier)) { try { return nextResolve(`${specifier}.ts`, context); } catch {} } return nextResolve(specifier, context); } });
const { exportPdf } = await import('../src/export-pdf.ts');
const { makeSamples } = await import('../src/text.ts');
const { initialExportOptions } = await import('../src/export-model.ts');
const { PDFDocument } = await import('pdf-lib');
const paper = makeSamples()[0];
paper.title = '栖页图表保留与中文排版验收';
paper.authors = '栖页原创软件验收 · 非发表论文';
paper.kind = 'pdf'; paper.pageCount = 3;
paper.translations[paper.blocks[0].id] = { text: '中文排版验收。95%置信区间与12个观测值仅作为字符样例，不代表真实研究结论。', engine: '人工校订', issues: [], createdAt: 1 };
paper.notes.push({ id: 'verification-note', text: '这是一条中文阅读笔记。保留原图、图注、坐标与表格，图表数据不得编造。\n' + '中英文混排 Reading notes with evidence, 95% interval. '.repeat(100), quote: paper.blocks[0].text, blockId: paper.blocks[0].id, createdAt: 1 });
const source = new Blob([await readFile(new URL('chart-fixture.pdf', import.meta.url))], { type: 'application/pdf' });
const font = await readFile(new URL('../public/fonts/QiyeSans-Regular.ttf', import.meta.url));
const original = JSON.stringify(paper), messages = [];
const ctx = { signal: new AbortController().signal, report: v => messages.push(v.message) };
const blob = await exportPdf({ paper, file: source }, initialExportOptions(true), ctx, font);
await writeFile(new URL('artifacts/pdf-regression.pdf', import.meta.url), Buffer.from(await blob.arrayBuffer()));
const document = await PDFDocument.load(await blob.arrayBuffer());
assert.ok(document.getPageCount() >= 8);
assert.equal(JSON.stringify(paper), original);
assert.equal(blob.type, 'application/pdf');
assert.deepEqual(document.getPages().slice(-3).map(p => [Math.round(p.getWidth()), Math.round(p.getHeight())]), [[595,842],[842,595],[595,842]]);
const stopped = new AbortController(); stopped.abort(new DOMException('cancelled', 'AbortError'));
await assert.rejects(exportPdf({ paper, file: source }, initialExportOptions(true), { signal: stopped.signal, report() {} }, font), { name: 'AbortError' });
await assert.rejects(exportPdf({ paper }, initialExportOptions(true), ctx, font), /原 PDF 不在本机/);
const bad = structuredClone(paper); bad.title = 'Unsupported \u{1f9ea}';
await assert.rejects(exportPdf({ paper: bad }, initialExportOptions(false), ctx, font), /字体暂不支持/);
const { PDFName, PDFRawStream } = await import('pdf-lib');
const repeated = await PDFDocument.create();
const bitmap = await repeated.embedPng(await readFile(new URL('artifacts/raster-pattern.png', import.meta.url)));
for (let i = 0; i < 70; i++) repeated.addPage([595,842]).drawImage(bitmap, { x: 40, y: 100, width: 480, height: 320 });
const repeatedSource = new Blob([new Uint8Array(await repeated.save()).buffer], { type: 'application/pdf' });
const repeatedPaper = structuredClone(paper); repeatedPaper.pageCount = 70;
const repeatedBlob = await exportPdf({ paper: repeatedPaper, file: repeatedSource }, { ...initialExportOptions(true), includeText: false, includeNotes: false, includeEvidence: false }, ctx, font);
const repeatedOutput = await PDFDocument.load(await repeatedBlob.arrayBuffer());
const imageCount = repeatedOutput.context.enumerateIndirectObjects().filter(([, value]) => value instanceof PDFRawStream && value.dict.get(PDFName.of('Subtype'))?.toString() === '/Image').length;
assert.equal(imageCount, 1, '70 pages must reuse the one shared bitmap');
console.log(JSON.stringify({ passed: true, bytes: blob.size, pages: document.getPageCount(), sharedImagePages: 70, embeddedImages: imageCount, repeatedSourceBytes: repeatedSource.size, repeatedOutputBytes: repeatedBlob.size, stages: [...new Set(messages)] }));
